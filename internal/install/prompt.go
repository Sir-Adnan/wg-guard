func renderBootConfig(p Plan) ([]byte, error) {
	var buf bytes.Buffer
	if err := toml.NewEncoder(&buf).Encode(p.BootConfig()); err != nil {
		return nil, err
	}
	return append([]byte("# Generated by wg-guard install; listener/TLS/path changes require restart.\n"), buf.Bytes()...), nil
}

type prompt struct {
	yes      bool
	advanced bool
	ui       *terminal.UI
	out      io.Writer
}

func newPrompt(in io.Reader, out io.Writer, yes bool) *prompt {
	return &prompt{yes: yes, ui: terminal.New(in, out, terminal.Detect(in, out, i18n.En)), out: out}
}
func (q *prompt) t(key string, args ...any) string { return q.ui.T("setup."+key, args...) }
func (q *prompt) ask(label, def string) (string, error) {
	if q.yes {
		return def, nil
	}
	return q.ui.Ask(label, def)
}
func (q *prompt) askInt(label string, def, min, max int) (int, error) {
	for {
		v, err := q.ask(label, strconv.Itoa(def))
		if err != nil {
			return 0, err
		}
		n, e := strconv.Atoi(terminal.Digits(v))
		if e == nil && n >= min && n <= max {
			return n, nil
		}
		if q.yes {
			return 0, fmt.Errorf("%s", q.t("range", min, max))
		}
		q.ui.Text(q.t("range", min, max))
	}
}
func (q *prompt) askChoice(label string, options []string, def int) (int, error) {
	if q.yes {
		return def, nil
	}
	return q.ui.Choose(label, options, def)
}
func (q *prompt) askSecret(label string) (string, error) {
	if q.yes {
		return "", nil
	}
	return q.ui.Secret(label)
}
func (q *prompt) askYesNo(label string, def bool) (bool, error) {
	if q.yes {
		return def, nil
	}
	return q.ui.ConfirmDefault(label, def)
}

// plan uses one streaming input object for every field, including hidden secrets.
// Back returns control to the caller; no partial plan is ever applied.
func (q *prompt) plan(p *Plan, h Host) error {
	if q.yes {
		return nil
	}
	q.ui.Locale = i18n.En
	q.ui.Header("WG-GUARD", q.t("subtitle"))
	q.ui.Text(q.t("intro"))
	q.advanced = advancedSettingsRequested(p)
	explicitAccess := p.ExposureExplicit || p.CertificateExplicit || p.TLSModeExplicit
	var err error
	q.ui.Section(q.t("access"))
	p.Domain, err = q.ask(q.t("domain"), p.Domain)
	if err != nil {
		return err
	}
	facts, err := InspectExposure(q.ui.Context, h, p.Domain)
	if err != nil {
		return err
	}
	recommended, recommendationErr := ResolveExposure(*p, facts)
	if recommendationErr == nil {
		*p = recommended
		q.ui.Success(q.t("recommended") + ": " + q.t("recommended_summary", q.t("access_"+string(p.Exposure))))
	} else {
		if explicitAccess {
			return recommendationErr
		}
		q.ui.Warning(q.t("conflict"))
		fallback := *p
		fallback.Exposure = ExposurePrivate
		fallback.Certificate = CertificateAuto
		fallback, err = ResolveExposure(fallback, facts)
		if err != nil {
			return recommendationErr
		}
		*p = fallback
		q.advanced = true
	}
	if !q.advanced {
		useRecommended, askErr := q.askYesNo(q.t("use_recommended"), true)
		err = askErr
		q.advanced = !useRecommended
		if err != nil {
			return err
		}
	}
	if !q.advanced {
		p.Mode = ModeDocker
		return nil
	}

	if !p.Mode.Valid() {
		n, e := q.askChoice(q.t("mode"), []string{q.t("docker"), q.t("native")}, 1)
		if e != nil {
			return e
		}
		p.Mode = ModeDocker
		if n == 2 {
			p.Mode = ModeNative
		}
	}
	if err := q.planAccess(p, facts, explicitAccess); err != nil {
		return err
	}
	if err := q.planNetwork(p); err != nil {
		return err
	}
	if err := q.planTelegram(p); err != nil {
		return err
	}
	if p.Mode == ModeDocker && p.Image == DefaultImage {
		customImage, askErr := q.askYesNo(q.t("custom_image"), false)
		if askErr != nil {
			return askErr
		}
		if customImage {
			p.Image, err = q.ask(q.t("image"), p.Image)
		}
	}
	return err
}

func (q *prompt) planAccess(p *Plan, facts ExposureFacts, explicit bool) error {
	var err error
	if !explicit {
		if p.Domain == "" {
			n, e := q.askChoice(q.t("access_method"), []string{q.t("private"), q.t("ip_https")}, 1)
			if e != nil {
				return e
			}
			if n == 1 {
				p.Exposure, p.Certificate = ExposurePrivate, ""
			} else {
				p.Exposure, p.Certificate = ExposureDirect, CertificateIP
				p.PublicIP, err = q.ask(q.t("ip"), p.PublicIP)
				if err != nil {
					return err
				}
			}
		} else {
			n, e := q.askChoice(q.t("access_method"), []string{q.t("use_detected", q.t("access_"+string(p.Exposure))), q.t("private"), q.t("other_access")}, 1)
			if e != nil {
				return e
			}
			switch n {
			case 2:
				p.Exposure, p.Certificate = ExposurePrivate, ""
			case 3:
				method, choiceErr := q.askChoice(q.t("other_access"), []string{q.t("direct"), q.t("managed_nginx"), q.t("external_proxy")}, 1)
				if choiceErr != nil {
					return choiceErr
				}
				switch method {
				case 1:
					p.Exposure, p.Certificate = ExposureDirect, CertificateAuto
				case 2:
					p.Exposure, p.Certificate = ExposureNginx, CertificateAuto
				case 3:
					p.Exposure, p.Certificate = ExposureExternalProxy, CertificateExternal
				}
			}
		}
	}

	if p.Exposure == ExposureDirect && p.Certificate == CertificateAuto {
		n, e := q.askChoice(q.t("certificate"), []string{q.t("cert_builtin"), q.t("cert_cloudflare"), q.t("cert_manual")}, 1)
		if e != nil {
			return e
		}
		p.Certificate = []CertificateSource{CertificateBuiltin, CertificateCloudflareDNS, CertificateManual}[n-1]
	}
	if p.Exposure == ExposureNginx && p.Certificate == CertificateAuto {
		n, e := q.askChoice(q.t("certificate"), []string{q.t("cert_webroot"), q.t("cert_cloudflare"), q.t("cert_manual"), q.t("cert_origin")}, 1)
		if e != nil {
			return e
		}
		p.Certificate = []CertificateSource{CertificateWebroot, CertificateCloudflareDNS, CertificateManual, CertificateCloudflareOrigin}[n-1]
	}
	if p.Certificate == CertificateCloudflareDNS && p.CloudflareToken == "" {
		p.CloudflareToken, err = q.askSecret(q.t("cloudflare_token"))
		if err != nil {
			return err
		}
		if !cloudflareAPIToken.MatchString(p.CloudflareToken) {
			return fmt.Errorf("%s", q.t("cloudflare_invalid"))
		}
	}
	if p.Certificate == CertificateManual || p.Certificate == CertificateCloudflareOrigin {
		p.CertFile, err = q.ask(q.t("cert"), p.CertFile)
		if err != nil {
			return err
		}
		p.KeyFile, err = q.ask(q.t("key"), p.KeyFile)
		if err != nil {
			return err
		}
	}

	switch p.Exposure {
	case ExposureDirect:
		def := p.PanelPort
		if !p.PanelPortExplicit && def == 8080 {
			def = 443
		}
		p.PanelPort, err = q.askInt(q.t("https_port"), def, 1, 65535)
		p.PublicPort = p.PanelPort
		p.PanelPortExplicit = true
		if err == nil && (p.Certificate == CertificateBuiltin || p.Certificate == CertificateIP) {
			q.ui.Warning(q.t("http01"))
			p.ACMEHTTPPort, err = q.askInt(q.t("acme_port"), p.ACMEHTTPPort, 1, 65535)
		}
	case ExposurePrivate:
		p.PanelPort, err = q.askInt(q.t("backend_port"), p.PanelPort, 1, 65535)
		p.PanelPortExplicit = true
	case ExposureNginx, ExposureExternalProxy:
		backend := p.PanelPort
		if !p.PanelPortExplicit && facts.BackendPort != 0 {
			backend = facts.BackendPort
		}
		p.PanelPort, err = q.askInt(q.t("backend_port"), backend, 1, 65535)
		p.PanelPortExplicit = true
		if err == nil {
			p.PublicPort, err = q.askInt(q.t("public_https_port"), p.PublicPort, 1, 65535)
		}
	}
	if err != nil {
		return err
	}
	if p.Certificate == CertificateBuiltin || p.Certificate == CertificateWebroot || p.Certificate == CertificateCloudflareDNS || p.Certificate == CertificateIP {
		p.ACMEEmail, err = q.ask(q.t("acme_email"), p.ACMEEmail)
		if err != nil {
			return err
		}
	}
	resolved, err := ResolveExposure(*p, facts)
	if err != nil {
		return err
	}
	*p = resolved
	return nil
}

func advancedSettingsRequested(p *Plan) bool {
	return p.Mode.Valid() || p.TLSModeExplicit || p.PanelPortExplicit || p.ACMEHTTPPort != 80 ||
		p.ExposureExplicit || p.CertificateExplicit || p.PublicPort != 443 || p.ACMEEmail != "" || p.CloudflareTokenFile != "" ||
		p.PublicIP != "" || p.CertFile != "" || p.KeyFile != "" || p.Image != DefaultImage
}

func (q *prompt) planNetwork(p *Plan) error {
	q.ui.Section(q.t("network"))
	q.ui.Text(q.t("network_defaults"))
	yes, err := q.askYesNo(q.t("custom_network"), false)
	if err != nil || !yes {
		return err
	}
	p.PortMin, err = q.askInt(q.t("port_min"), 30000, 1024, 65535)
	if err != nil {
		return err
	}
	for {
		p.PortMax, err = q.askInt(q.t("port_max"), 50000, 1024, 65535)
		if err != nil {
			return err
		}
		if p.PortMax >= p.PortMin {
			break
		}
		q.ui.Text(q.t("port_order"))
	}
	for {
		p.VPNSubnet, err = q.ask(q.t("pool"), builtInPool)
		if err != nil {
			return err
		}
		if settings.ValidSubnet(p.VPNSubnet) == nil {
			break
		}
		q.ui.Text(q.t("cidr_invalid"))
	}
	if p.VPNSubnet == builtInPool {
		p.VPNSubnet = ""
	}
	p.MTU, err = q.askInt(q.t("mtu"), 1420, 576, 65535)
	if err != nil {
		return err
	}
	for {
		p.ClientDNS, err = q.ask(q.t("dns"), "1.1.1.1, 1.0.0.1")
		if err != nil {
			return err
		}
		if validIPList(p.ClientDNS) {
			break
		}
		q.ui.Text(q.t("dns_invalid"))
	}
	return nil
}
func (q *prompt) planTelegram(p *Plan) error {
	q.ui.Section(q.t("backup"))
	yes, err := q.askYesNo(q.t("telegram"), false)
	if err != nil || !yes {
		return err
	}
	token, err := q.askSecret(q.t("token"))
	if err != nil {
		return err
	}
	if token == "" {
		q.ui.Text(q.t("token_skipped"))
		return nil
	}
	for {
		p.TelegramChat, err = q.ask(q.t("chat"), "")
		if err != nil {
			return err
		}
		p.TelegramChat = terminal.Digits(p.TelegramChat)
		if validChatID(p.TelegramChat) {
			break
		}
		q.ui.Text(q.t("chat_invalid"))
	}
	for {
		p.TelegramTime, err = q.ask(q.t("time"), "03:30")
		if err != nil {
			return err
		}
		p.TelegramTime = terminal.Digits(p.TelegramTime)
		if dailyTimeRe.MatchString(p.TelegramTime) {
			break
		}
		q.ui.Text(q.t("time_invalid"))
	}
	p.TelegramToken = token
	return nil
}
func (q *prompt) confirm(p Plan) error {
	if q.yes {
		return nil
	}
	q.ui.Locale = i18n.En
	q.ui.Section(q.t("review"))
	certificate := string(p.Certificate)
	if certificate == "" {
		certificate = q.t("not_applicable")
	}
	fields := []struct{ k, v string }{
		{"mode", string(p.Mode)}, {"access_method", string(p.Exposure)}, {"certificate", certificate},
		{"panel", p.PanelURL()}, {"endpoint", p.VPNEndpoint()},
	}
	if q.advanced {
		fields = append(fields, struct{ k, v string }{"config", p.BootConfigPath()}, struct{ k, v string }{"data", p.DataDir})
	}
	for _, field := range fields {
		q.ui.Field(q.t(field.k), field.v)
	}
	if q.advanced && p.Mode == ModeDocker {
		q.ui.Field(q.t("image"), p.Image)
	}
	lo, hi := p.PortMin, p.PortMax
	if lo == 0 {
		lo = 30000
	}
	if hi == 0 {
		hi = 50000
	}
	if q.advanced {
		q.ui.Field(q.t("udp"), fmt.Sprintf("%d–%d", lo, hi))
		if p.Exposure != ExposureDirect {
			q.ui.Field(q.t("backend_port"), strconv.Itoa(p.PanelPort))
		}
		if p.Exposure == ExposureDirect {
			q.ui.Field(q.t("public_https_port"), strconv.Itoa(p.PanelPort))
		} else if p.PublicURL() != "" {
			q.ui.Field(q.t("public_https_port"), strconv.Itoa(p.PublicPort))
		}
	}
	pool, mtu, dns := p.VPNSubnet, p.MTU, p.ClientDNS
	if pool == "" {
		pool = "10.8.0.0/24"
	}
	if mtu == 0 {
		mtu = 1420
	}
	if dns == "" {
		dns = "1.1.1.1, 1.0.0.1"
	}
	if q.advanced {
		q.ui.Field(q.t("pool"), pool)
		q.ui.Field(q.t("mtu"), strconv.Itoa(mtu))
		q.ui.Field(q.t("dns"), dns)
	}
	if p.Certificate == CertificateBuiltin || p.Certificate == CertificateWebroot || p.Certificate == CertificateIP {
		q.ui.Warning(q.t("http01"))
	}
	if p.TelegramToken != "" {
		q.ui.Field(q.t("backup"), q.t("backup_set", p.TelegramChat, p.TelegramTime))
	} else if q.advanced {
		q.ui.Text(q.t("backup_later"))
	}
	q.ui.Info(q.t("impact"))
	ok, err := q.askYesNo(q.t("proceed"), true)
	if err != nil {
		return err
	}
	if !ok {
		return terminal.ErrCanceled
	}
	return nil
}
func validChatID(s string) bool {
	if s == "" || strings.HasPrefix(s, "+") {
		return false
	}
	n, err := strconv.ParseInt(s, 10, 64)
	return err == nil && n != 0
}

var dailyTimeRe = regexp.MustCompile(`^([01]\d|2[0-3]):[0-5]\d$`)

func validIPList(s string) bool {
	for _, part := range strings.Split(s, ",") {
		part = strings.TrimSpace(part)
		if part == "" || net.ParseIP(part) == nil {
			return false
		}
	}
	return true
}
func isDigits(s string) bool {
	if s == "" {
		return false
	}
	for _, r := range s {
		if r < '0' || r > '9' {
			return false
		}
	}
	return true
}
